const clamp = (v, a, b) => (v < a ? a : v > b ? b : v);
const smooth = (t) => t * t * (3 - 2 * t);

export class LetterField {
  constructor(el) {
    this.el = el;
    /* усі літери одного кеглю — без перспективних скорочень */
    this.nodes = GLYPHS.map((g) => {
      const b = document.createElement('b');
      b.textContent = g;
      el.appendChild(b);
      return { b, w: 0, h: 0 };
    });

    this.progress = 0;      /* цільовий прогрес скролу 0..1 */
    this.eased = 0;         /* згладжений */
    this.mx = 0; this.my = 0;
    this.tmx = 0; this.tmy = 0;
    this.vw = 0; this.vh = 0;
    this.dim = 1;           /* приглушення поза першим екраном */
    this.tdim = 1;
    this.keepOut = null;    /* зона, в яку літери не заходять */

    this.resize();
    addEventListener('resize', () => this.resize(), { passive: true });
    addEventListener('pointermove', (e) => {
      this.tmx = (e.clientX / this.vw - 0.5) * 2;
      this.tmy = (e.clientY / this.vh - 0.5) * 2;
    }, { passive: true });
  }

  resize() {
    this.vw = innerWidth;
    this.vh = innerHeight;
    for (const n of this.nodes) {
      n.w = n.b.offsetWidth;
      n.h = n.b.offsetHeight;
    }
  }

  /** p — прогрес скролу всього документа 0..1; dim — цільова непрозорість поля */
  setProgress(p, dim) {
    this.progress = clamp(p, 0, 1);
    this.tdim = dim;
  }

  /** прямокутник у пікселях вьюпорта, який літери обходять (або null) */
  setKeepOut(rect, pad = 16) {
    this.keepOut = rect && {
      cx: rect.x + rect.w / 2,
      cy: rect.y + rect.h / 2,
      hw: rect.w / 2 + pad,
      hh: rect.h / 2 + pad,
    };
  }

  /** виштовхує центр літери за межі забороненої зони по найкоротшому шляху */
  _avoid(cx, cy, hw, hh) {
    const k = this.keepOut;
    if (!k) return [cx, cy];
    const dx = cx - k.cx, dy = cy - k.cy;
    const ex = k.hw + hw, ey = k.hh + hh;      /* зона, розширена на розмір літери */
    const nx = Math.abs(dx) / ex, ny = Math.abs(dy) / ey;
    const m = Math.max(nx, ny);
    if (m >= 1) return [cx, cy];
    /* масштабуємо зміщення від центру так, щоб літера сіла рівно на межу —
       функція неперервна, тому літера не смикається при переході */
    const s = m < 1e-4 ? 1e4 : 1 / m;
    return [k.cx + dx * s, k.cy + dy * s];
  }

  update() {
    /* інерція скролу — літери «доганяють» */
    this.eased += (this.progress - this.eased) * 0.075;
    this.mx += (this.tmx - this.mx) * 0.05;
    this.my += (this.tmy - this.my) * 0.05;
    this.dim += (this.tdim - this.dim) * 0.06;

    const n = COMPOSITIONS.length;
    const u = this.eased * (n - 1);
    const i = Math.min(Math.floor(u), n - 2);
    const f = smooth(clamp(u - i, 0, 1));
    const A = COMPOSITIONS[i];
    const B = COMPOSITIONS[i + 1];

    for (let k = 0; k < this.nodes.length; k++) {
      const node = this.nodes[k];
      const a = A[k], b = B[k];

      /* кожна літера доїжджає з невеликим зсувом у часі — «розліт» */
      const lag = ((k * 0.11) % 1) * 0.35;
      const ff = smooth(clamp((f - lag) / (1 - lag), 0, 1));

      const fx = a[0] + (b[0] - a[0]) * ff;
      const fy = a[1] + (b[1] - a[1]) * ff;
      const fr = a[2] + (b[2] - a[2]) * ff;

      /* дуга: під час переходу літера трохи «підлітає» вбік */
      const arc = Math.sin(ff * Math.PI) * (b[0] - a[0]) * 0.18;

      let cx = fx * this.vw + this.mx * 14;
      let cy = fy * this.vh + this.my * 10 - arc * this.vh * 0.25;
      [cx, cy] = this._avoid(cx, cy, node.w / 2, node.h / 2);

      const px = cx - node.w / 2;
      const py = cy - node.h / 2;
      node.b.style.transform =
        `translate3d(${px.toFixed(1)}px, ${py.toFixed(1)}px, 0) rotate(${fr.toFixed(2)}deg)`;
    }

    this.el.style.opacity = this.dim.toFixed(3);
  }
}
